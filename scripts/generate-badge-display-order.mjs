import { readFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';

export function generateBadgeDisplayOrder(catalog) {
  if (!Array.isArray(catalog?.badges) || catalog.badges.some((badge) => typeof badge.key !== 'string'
    || !Number.isFinite(badge.displayOrder))) throw new TypeError('A canonical badge key/order catalog is required.');
  // Preserve catalog order and duplicates: consumers retain first-match semantics.
  const pairs = catalog.badges.map(({ key, displayOrder }) => [key, displayOrder]);
  return '// Generated by scripts/generate-badge-display-order.mjs; do not edit by hand.\n'
    + 'export const BADGE_DISPLAY_ORDER = Object.freeze(' + JSON.stringify(pairs)
    + '.map((entry) => Object.freeze(entry)));\n';
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const catalog = JSON.parse(await readFile(new URL('../src/static/badge-catalog.v1.json', import.meta.url), 'utf8'));
  const generated = generateBadgeDisplayOrder(catalog);
  if (process.argv.includes('--check')) {
    const actual = await readFile(new URL('../src/static/badge-display-order.generated.mjs', import.meta.url), 'utf8');
    if (actual !== generated) throw new Error('Badge display-order projection is stale. Regenerate it from the canonical catalog.');
    console.log('Canonical badge display-order projection matches.');
  } else process.stdout.write(generated);
}
